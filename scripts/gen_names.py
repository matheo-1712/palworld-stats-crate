"""Generates `src/names/data.rs` from Palworld-Pal-Editor's data files.

Usage:
    python scripts/gen_names.py <pal_data.json> <human_data.json> <pal_passives.json>

Source: https://github.com/KrisCris/Palworld-Pal-Editor
(`src/palworld_pal_editor/assets/data/`). The names are the official in-game
texts extracted from the game files. Re-run after a game update that adds pals
or passive skills.
"""

import json
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src" / "names" / "data.rs"


def rust_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def main() -> None:
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    # Captured humans are owned "pals" too, with the same data layout
    pals = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    pals.update(json.loads(Path(sys.argv[2]).read_text(encoding="utf-8")))
    passives = json.loads(Path(sys.argv[3]).read_text(encoding="utf-8"))

    pal_rows = []
    for pal_id, pal in pals.items():
        i18n = pal.get("I18n") or {}
        en, fr = i18n.get("en"), i18n.get("fr")
        if not en or not fr:
            continue
        family = pal.get("FamilyID") or pal_id
        pal_rows.append((pal_id.lower(), pal_id, family, en, fr))
    pal_rows.sort()

    passive_rows = []
    for skill_id, skill in passives.items():
        i18n = skill.get("I18n") or {}
        en = (i18n.get("en") or {}).get("Name")
        fr = (i18n.get("fr") or {}).get("Name")
        if not en or not fr:
            continue
        passive_rows.append((skill_id.lower(), skill_id, en, fr))
    passive_rows.sort()

    lines = [
        "// @generated by scripts/gen_names.py, do not edit by hand.",
        "// Official in-game names, extracted by Palworld-Pal-Editor",
        "// (https://github.com/KrisCris/Palworld-Pal-Editor).",
        "",
        "/// `(lowercase id, id, family id, en, fr)`, sorted by lowercase id.",
        "pub(super) static PALS: &[(&str, &str, &str, &str, &str)] = &[",
    ]
    for key, pal_id, family, en, fr in pal_rows:
        lines.append(
            f"    ({rust_str(key)}, {rust_str(pal_id)}, {rust_str(family)}, {rust_str(en)}, {rust_str(fr)}),"
        )
    lines += [
        "];",
        "",
        "/// `(lowercase id, id, en, fr)`, sorted by lowercase id.",
        "pub(super) static PASSIVES: &[(&str, &str, &str, &str)] = &[",
    ]
    for key, skill_id, en, fr in passive_rows:
        lines.append(f"    ({rust_str(key)}, {rust_str(skill_id)}, {rust_str(en)}, {rust_str(fr)}),")
    lines.append("];")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(pal_rows)} pals, {len(passive_rows)} passives -> {OUT}")


if __name__ == "__main__":
    main()
